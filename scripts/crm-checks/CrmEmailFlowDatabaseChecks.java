final class CrmEmailFlowDatabaseChecks {
    static void run(CrmEmailDatabaseChecks suite) throws Exception {
        CrmCampaign campaign = suite.campaign("真实闭环");
        CrmLead alice = suite.lead("Alice <&>", "Alice@example.com", 10, 0);
        CrmLead duplicate = suite.lead("Duplicate", "Alice@EXAMPLE.COM", 10, 0);
        CrmLead bob = suite.lead("Bob", "bob@example.com", 10, 0);
        CrmLead optedOut = suite.lead("OptedOut", "opt@example.com", 10, 1);
        CrmLead invalid = suite.lead("Invalid", "invalid", 10, 0);
        CrmLead excluded = suite.lead("Excluded", "excluded@example.com", 10, 0);
        CrmLead suppressed = suite.lead("Suppressed", "suppressed@example.com", 10, 0);
        CrmLead invisible = suite.lead("Invisible", "invisible@example.com", 11, 0);
        suite.list(campaign, false, alice, duplicate, bob, optedOut, invalid, excluded, suppressed, invisible);
        suite.list(campaign, false, alice);
        suite.list(campaign, true, excluded);
        suite.jdbc.update("INSERT INTO crm_email_suppression (tenant_id,email_hash,unsubscribed_time) VALUES (?,?,NOW())", suite.TENANT, CrmEmailSecurity.emailHash(suppressed.getEmail()));
        CrmEmailAudienceService.Audience audience = suite.audience.collect(campaign.getCampaignId(), suite.access.current());
        suite.equal(7, audience.counts().get("includedCount"), "scoped include union excludes inaccessible lead");
        suite.equal(1, audience.counts().get("excludedCount"), "excluded list removes target");
        suite.equal(2, audience.counts().get("optedOutCount"), "source opt-out plus email suppression");
        suite.equal(1, audience.counts().get("invalidEmailCount"), "invalid mailbox removed");
        suite.equal(1, audience.counts().get("duplicateCount"), "canonical mailbox deduplicated");
        suite.equal(2, audience.counts().get("recipientCount"), "exact eligible recipients");
        suite.check(!suite.json.writeValueAsString(audience.view()).contains("Alice@example.com"), "audience view masks personal email");
        CrmMassEmail draft = suite.draft(campaign);
        long id = draft.getMassEmailId();
        suite.identity(11);
        suite.rejects(() -> suite.campaigns.preview(id), "peer cannot read or send owner's campaign");
        suite.identity(5);
        suite.check(!suite.access.current().sending(), "employee lacks marketing write permission");
        suite.rejects(() -> suite.campaigns.save(new CrmMassEmailDraft(null, campaign.getCampaignId(), null, "Bad", "CRM_MARKETING", null, null, null)), "employee cannot create a marketing draft");
        suite.identity(10);
        TenantContext.setTenantId(suite.TENANT + 1); UserContext.setTenantId(suite.TENANT + 1);
        suite.rejects(() -> suite.campaigns.list(campaign.getCampaignId()), "cross-tenant campaign read denied"); suite.identity(10);
        CrmMassEmail filled = suite.campaigns.save(new CrmMassEmailDraft(id, campaign.getCampaignId(), draft.getVersion(), draft.getSubject(), "CRM_MARKETING", "sender@example.com", "Custom", "reply@example.com"));
        suite.campaigns.save(new CrmMassEmailDraft(id, campaign.getCampaignId(), filled.getVersion(), draft.getSubject(), "CRM_MARKETING", null, null, null));
        CrmMassEmail cleared = suite.task(id);
        suite.check(cleared.getFromAddress() == null && cleared.getFromName() == null && cleared.getReplyTo() == null, "explicitly cleared optional headers persisted as SQL NULL");
        CrmMassEmailCommand stalePreview = suite.command(cleared, null, null);
        suite.setting("crm.email.confirmationThreshold", "1");
        suite.rejects(() -> suite.campaigns.send(id, stalePreview), "preview digest detects changed policy");
        Map<String, Object> preview = suite.campaigns.preview(id);
        suite.equal(true, preview.get("requiresConfirmation"), "exact recipient count triggers second confirmation");
        CrmMassEmailCommand missingConfirm = new CrmMassEmailCommand((Integer) preview.get("version"), (String) preview.get("previewDigest"), false, 2, null, null);
        suite.rejects(() -> suite.campaigns.send(id, missingConfirm), "large campaign cannot bypass confirmation");
        suite.equal(0L, suite.scalar("SELECT COUNT(*) FROM crm_mass_email_recipient WHERE mass_email_id=?", id), "rejected confirmation creates no snapshots");
        suite.setting("crm.email.sendingEnabled", "false");
        suite.equal(false, suite.campaigns.preview(id).get("ready"), "unconfigured capability explicitly disabled");
        suite.rejects(() -> suite.send(suite.task(id)), "disabled email cannot create outbox work");
        suite.setting("crm.email.sendingEnabled", "true");
        suite.jdbc.update("UPDATE sys_message_template SET force_send_flag=1 WHERE template_id=100");
        suite.equal(false, suite.campaigns.preview(id).get("ready"), "force-send template unavailable for marketing");
        suite.jdbc.update("UPDATE sys_message_template SET force_send_flag=0 WHERE template_id=100");
        int beforeTest = suite.smtp.count();
        CrmMassEmailCommand testCommand = suite.command(suite.task(id), null, "only-test@example.com");
        CrmMassEmailRecipient test = suite.campaigns.test(id, testCommand);
        suite.equal(test.getRecipientId(), suite.campaigns.test(id, testCommand).getRecipientId(), "unchanged test submission reuses one frozen recipient");
        suite.equal("CRM_MASS_EMAIL:" + test.getRecipientId(), suite.snapshots.request(suite.recipient(test.getRecipientId())).getTraceId(), "frozen content carries stable trace identity before dispatch enrichment");
        suite.pump();
        suite.equal(beforeTest + 1, suite.smtp.count(), "exactly one test email accepted over TLS");
        suite.equal("only-test@example.com", suite.smtp.message(beforeTest).getAllRecipients()[0].toString(), "test sends only to explicit mailbox");
        suite.equal(1, suite.recipient(test.getRecipientId()).getTestFlag(), "test snapshot marked as test");
        suite.equal(0, suite.mapper(CrmCampaignMapper.class).selectById(campaign.getCampaignId()).getSentCount(), "test acceptance excluded from formal counters");
        suite.tracking.open(suite.tokens(suite.recipient(test.getRecipientId()), "open").get(0), "e5-check", "192.0.2.10");
        suite.equal(0, suite.mapper(CrmCampaignMapper.class).selectById(campaign.getCampaignId()).getOpenedCount(), "test observations excluded from formal counters");
        CrmMassEmail original = suite.task(id);
        suite.campaigns.save(new CrmMassEmailDraft(id, campaign.getCampaignId(), original.getVersion(), "New {{contactName}} · {{campaignName}}", "CRM_MARKETING", null, null, null));
        suite.rejects(() -> suite.campaigns.test(id, suite.command(suite.task(id), null, "only-test@example.com")), "changed draft does not silently reuse old test content");
        int beforeFormal = suite.smtp.count();
        suite.send(suite.task(id));
        suite.equal("SENDING", suite.task(id).getStatus(), "outbox registration never reports accepted mail");
        suite.equal(2, suite.task(id).getTotalCount(), "formal snapshot excludes test mailbox");
        suite.equal(3, suite.recipients(id).size(), "one test plus two formal recipient snapshots");
        suite.equal(0, suite.campaigns.dispatchBatch(id, 100), "duplicate dispatch cannot repeat queued work");
        suite.rejects(() -> suite.campaigns.send(id, suite.command(suite.task(id), null, null)), "repeated send cannot freeze another audience");
        suite.pump();
        suite.equal(beforeFormal + 2, suite.smtp.count(), "both formal recipients accepted separately");
        suite.equal("SENT", suite.task(id).getStatus(), "all accepted formal recipients complete task");
        List<CrmMassEmailRecipient> formal = suite.recipients(id).stream().filter(recipient -> recipient.getTestFlag() == 0).toList();
        for (CrmMassEmailRecipient recipient : formal) {
            suite.equal("SENT", recipient.getStatus(), "auth acceptance projected to recipient");
            suite.equal(2, suite.tokens(recipient, "click").size(), "each distinct target has independent token");
            String address = suite.snapshots.request(recipient).safeReceivers().get(0).getReceiverAddress();
            String open = suite.tokens(recipient, "open").get(0);
            String response = suite.json.writeValueAsString(suite.campaigns.detail(id, new PageQuery()));
            for (String sensitive : List.of(address, open, recipient.getEmailEncrypted(), recipient.getVariableSnapshotEncrypted(), recipient.getOpenTokenHash())) {
                suite.check(!response.contains(sensitive), "ordinary detail hides ciphertext, hashes, addresses and tracking token");
                suite.check(!recipient.toString().contains(sensitive), "recipient string hides protected values");
            }
            String outboxes = String.join("", suite.jdbc.queryForList("SELECT payload_json FROM outbox_event WHERE tenant_id=?", String.class, suite.TENANT));
            suite.check(!outboxes.contains(open) && !outboxes.contains(address), "outbox contains no unencrypted email or token");
        }
        String body = body(suite.smtp.message(beforeFormal));
        suite.check(body.contains("Alice &lt;&amp;&gt;") && body.contains("Company Alice &lt;&amp;&gt;"), "personalized HTML escaped exactly once");
        suite.check(!body.contains("{{contactName}}") && body.contains("确认退订"), "personalization replaced and unsubscribe mandatory");
        for (int index = beforeFormal; index < suite.smtp.count(); index++) {
            MimeMessage message = suite.smtp.message(index);
            suite.equal(1, message.getAllRecipients().length, "each message has exactly one recipient");
            suite.check(message.getHeader("Cc") == null && message.getHeader("Bcc") == null, "no cross-recipient headers");
        }
        CrmMassEmailRecipient observed = formal.get(0);
        String openToken = suite.tokens(observed, "open").get(0);
        suite.tracking.open(openToken, "e5-check", "192.0.2.10");
        CrmCampaign afterOpen = suite.mapper(CrmCampaignMapper.class).selectById(campaign.getCampaignId());
        suite.equal(1, afterOpen.getOpenedCount(), "first real observation counts once");
        suite.tracking.open(openToken, "e5-check", "192.0.2.10");
        suite.equal(afterOpen.getVersion(), suite.mapper(CrmCampaignMapper.class).selectById(campaign.getCampaignId()).getVersion(), "repeated observations do not invalidate unchanged campaign previews");
        List<String> clickTokens = suite.tokens(observed, "click");
        suite.equal("https://example.com/offer?a=1&b=2", suite.tracking.click(clickTokens.get(0), "e5-check", "192.0.2.10"), "click resolves canonical stored destination");
        suite.equal("https://example.com/terms", suite.tracking.click(clickTokens.get(1), "e5-check", "192.0.2.10"), "second link resolves its own destination");
        suite.equal(1, suite.mapper(CrmCampaignMapper.class).selectById(campaign.getCampaignId()).getClickedCount(), "multiple links count one unique recipient");
        suite.rejects(() -> suite.tracking.click(openToken, "e5-check", "192.0.2.10"), "open token cannot authorize click");
        suite.rejects(() -> suite.tracking.unsubscribe(openToken, null, "e5-check", "192.0.2.10"), "open token cannot authorize unsubscribe");
        suite.setting("crm.email.allowedHosts", "news.example.com");
        suite.rejects(() -> suite.tracking.click(clickTokens.get(0), "e5-check", "192.0.2.10"), "removed host rejected by current allowlist");
        suite.setting("crm.email.allowedHosts", "example.com");
        suite.setting("crm.email.trackingEnabled", "false");
        suite.rejects(() -> suite.tracking.click(clickTokens.get(0), "e5-check", "192.0.2.10"), "observation switch disables click tracking");
        String unsubscribe = suite.tokens(observed, "unsubscribe").get(0);
        suite.check(suite.tracking.validUnsubscribe(unsubscribe), "unsubscribe remains valid when observation disabled");
        suite.jdbc.update("UPDATE crm_campaign SET status='COMPLETED' WHERE campaign_id=?", campaign.getCampaignId());
        String observationAgent = "test ".repeat(97);
        suite.tracking.unsubscribe(unsubscribe, "不再接收 " + unsubscribe + " " + openToken, observationAgent + unsubscribe, "192.0.2.10");
        String savedReason = suite.jdbc.queryForObject("SELECT reason FROM crm_email_suppression WHERE tenant_id=? AND email_hash=?", String.class, suite.TENANT, observed.getEmailHash());
        suite.check("不再接收 [redacted] [redacted]".equals(savedReason), "unsubscribe reason retains business text without persisting raw tracking tokens");
        String savedAgent = suite.jdbc.queryForObject("SELECT user_agent FROM crm_campaign_log WHERE tenant_id=? AND source_event_key=?", String.class, suite.TENANT, "MAIL:" + observed.getRecipientId() + ":UNSUBSCRIBED");
        suite.check((observationAgent + "[redacted]").equals(savedAgent), "observation token is redacted before the 500-character storage boundary");
        suite.tracking.unsubscribe(unsubscribe, "重复", "e5-check", "192.0.2.10");
        suite.check(savedReason.equals(suite.jdbc.queryForObject("SELECT reason FROM crm_email_suppression WHERE tenant_id=? AND email_hash=?", String.class, suite.TENANT, observed.getEmailHash())), "duplicate unsubscribe preserves the first sanitized reason");
        suite.equal(1L, suite.scalar("SELECT COUNT(*) FROM crm_email_suppression WHERE tenant_id=? AND email_hash=?", suite.TENANT, observed.getEmailHash()), "repeated unsubscribe inserts one suppression");
        suite.equal(1L, suite.scalar("SELECT unsubscribe_flag FROM crm_lead WHERE lead_id=?", observed.getTargetId()), "source lead marked opted out immediately");
        suite.equal(1, suite.mapper(CrmCampaignMapper.class).selectById(campaign.getCampaignId()).getUnsubscribedCount(), "unsubscribe counted once for accepted recipient");
        suite.equal(1, suite.audience.collect(campaign.getCampaignId(), suite.access.current()).recipients().size(), "duplicate source mailbox also excluded after unsubscribe");
        suite.setting("crm.email.trackingEnabled", "true"); suite.setting("crm.email.confirmationThreshold", "5000");
        CrmCampaign scheduled = suite.campaign("定时发送"); suite.list(scheduled, false, suite.lead("Scheduled", "scheduled@example.com", 10, 0));
        CrmMassEmail future = suite.draft(scheduled);
        LocalDateTime scheduledAt = LocalDateTime.now().plusHours(1).withNano(123456000);
        suite.campaigns.schedule(future.getMassEmailId(), suite.command(future, scheduledAt, null));
        suite.equal(scheduledAt.withNano(0).plusSeconds(1), suite.task(future.getMassEmailId()).getScheduledTime(), "second-precision storage never advances fractional scheduled time");
        suite.equal(0, suite.campaigns.dispatchBatch(future.getMassEmailId(), 100), "future schedule cannot dispatch early");
        suite.jdbc.update("UPDATE crm_mass_email SET scheduled_time=DATE_SUB(NOW(),INTERVAL 1 SECOND) WHERE mass_email_id=?", future.getMassEmailId());
        suite.equal(1, suite.campaigns.dispatch(), "due scan advances one frozen recipient"); suite.pump();
        suite.equal("SENT", suite.task(future.getMassEmailId()).getStatus(), "scheduled frozen recipient accepted");
        System.out.println("E5_FLOW: selection=true; ownership=true; configuration_disabled=true; test_isolated=true; real_tls_personalization=true; tracking_deduplicated=true; unsubscribe_persistent=true; scheduled_due_scan=true");
    }

    static String body(Part part) throws Exception {
        if (!part.isMimeType("multipart/*")) return part.isMimeType("text/*") ? String.valueOf(part.getContent()) : "";
        Multipart multipart = (Multipart) part.getContent(); StringBuilder result = new StringBuilder();
        for (int index = 0; index < multipart.getCount(); index++) result.append(body(multipart.getBodyPart(index)));
        return result.toString();
    }
}
