public enum FileStorageType {

    LOCAL,

    OSS;

    /**
     * ????????????????????
     * ???null / '' / 'local' ????? LOCAL?
     */
    public static FileStorageType fromValue(String value) {
        if (StrUtil.isBlank(value)) {
            return LOCAL;
        }
        for (FileStorageType item : values()) {
            if (item.name().equalsIgnoreCase(value.trim())) {
                return item;
            }
        }
        return LOCAL;
    }
}
